#!/usr/bin/env bash
# Resolves controller/plugins.txt, dependencies included, and writes every plugin at its exact version to
# controller/plugins.lock.txt. Run it when you change plugins.txt, review the diff, commit both files.
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
require docker

image="$(sed -n 's/^ARG JENKINS_IMAGE=//p' "${ROOT}/controller/Dockerfile")"
work="$(mktemp -d)"
trap 'rm -rf "${work}"' EXIT
grep -vE '^\s*(#|$)' "${ROOT}/controller/plugins.txt" > "${work}/plugins.txt"

log "resolving plugins on ${image%%@*}"
docker run --rm --user root -v "${work}:/work" "${image}" bash -c '
  set -e
  jenkins-plugin-cli --plugin-file /work/plugins.txt --plugin-download-directory /work/plugins >/dev/null
  for file in /work/plugins/*.jpi /work/plugins/*.hpi; do
    [ -f "${file}" ] || continue
    name="$(basename "${file}" | sed -E "s/\.(jpi|hpi)$//")"
    version="$(unzip -p "${file}" META-INF/MANIFEST.MF | tr -d "\r" | sed -n "s/^Plugin-Version: //p")"
    echo "${name}:${version}"
  done | sort
' > "${work}/lock.txt"

{
  echo "# Generated by scripts/plugins-lock.sh from plugins.txt on the Jenkins image in the Dockerfile. Do not edit by hand."
  cat "${work}/lock.txt"
} > "${ROOT}/controller/plugins.lock.txt"
log "wrote $(grep -vc '^#' "${ROOT}/controller/plugins.lock.txt") plugins to controller/plugins.lock.txt"
